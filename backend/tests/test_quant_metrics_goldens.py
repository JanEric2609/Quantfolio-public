def _expect(name: str, key: str) -> float:
    """QuantStats' NaN/Inf maps onto this module's 0.0 contract."""
    value = GOLDENS[name]["expected"][key]
    return 0.0 if value is None else value


@pytest.mark.parametrize("name", _FIXTURES)
@pytest.mark.parametrize("periods", [252, 365])
def test_volatility_matches_quantstats_0_0_81(name, periods):
    rs = GOLDENS[name]["returns"]
    assert annualised_volatility(rs, periods_per_year=periods) == pytest.approx(
        _expect(name, f"volatility_{periods}"), rel=1e-12
    )


