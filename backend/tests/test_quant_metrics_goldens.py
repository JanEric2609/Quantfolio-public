def test_quantstats_is_no_longer_importable_from_app_code():
    """The dependency is gone from pyproject; nothing in app/ may reach for it."""
    import pathlib

    app = pathlib.Path(__file__).resolve().parent.parent / "app"
    offenders = [
        str(f.relative_to(app))
        for f in app.rglob("*.py")
        if "quantstats" in f.read_text()
    ]
    assert offenders == []
